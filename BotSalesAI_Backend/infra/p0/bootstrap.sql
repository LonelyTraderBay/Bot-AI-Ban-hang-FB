\set ON_ERROR_STOP on
\getenv migration_password BOTSALES_DB_MIGRATION_PASSWORD
\getenv runtime_password BOTSALES_DB_RUNTIME_PASSWORD

BEGIN;
SET LOCAL password_encryption = 'scram-sha-256';
CREATE ROLE botsales_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION PASSWORD :'migration_password';
CREATE ROLE botsales_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION PASSWORD :'runtime_password';

REVOKE CONNECT, TEMPORARY ON DATABASE :"DBNAME" FROM PUBLIC;
GRANT CONNECT ON DATABASE :"DBNAME" TO botsales_migrator, botsales_runtime;
ALTER DATABASE :"DBNAME" SET timezone TO 'UTC';

REVOKE ALL ON SCHEMA public FROM PUBLIC;
ALTER SCHEMA public OWNER TO botsales_migrator;
GRANT USAGE ON SCHEMA public TO botsales_runtime;
COMMIT;

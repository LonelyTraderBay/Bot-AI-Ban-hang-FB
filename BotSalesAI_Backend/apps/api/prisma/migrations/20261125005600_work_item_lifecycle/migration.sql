BEGIN;

ALTER TABLE owner_digests ADD COLUMN work_summary jsonb;

CREATE TABLE work_item_lifecycle (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id uuid NOT NULL,
    work_item_id uuid NOT NULL,
    state work_item_state NOT NULL,
    occurred_at timestamptz(6) NOT NULL,
    baseline boolean NOT NULL DEFAULT false,
    CONSTRAINT work_item_lifecycle_shop_id_work_item_id_fkey
        FOREIGN KEY (shop_id, work_item_id) REFERENCES work_items(shop_id, id)
        ON DELETE CASCADE ON UPDATE NO ACTION
);

CREATE INDEX work_item_lifecycle_lookup_idx
    ON work_item_lifecycle (shop_id, work_item_id, occurred_at DESC, event_id DESC);

LOCK TABLE work_items IN SHARE ROW EXCLUSIVE MODE;

-- For old work items, record what is known at migration time without inferring
-- a historical completion from an unrelated updated_at value.
INSERT INTO work_item_lifecycle (shop_id, work_item_id, state, occurred_at, baseline)
SELECT shop_id, id, state, CURRENT_TIMESTAMP, true FROM work_items;

CREATE FUNCTION capture_work_item_lifecycle() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.work_item_lifecycle (shop_id, work_item_id, state, occurred_at)
        VALUES (NEW.shop_id, NEW.id, NEW.state, NEW.created_at);
    ELSIF NEW.state IS DISTINCT FROM OLD.state THEN
        INSERT INTO public.work_item_lifecycle (shop_id, work_item_id, state, occurred_at)
        VALUES (NEW.shop_id, NEW.id, NEW.state, clock_timestamp());
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER capture_work_item_lifecycle
AFTER INSERT OR UPDATE OF state ON work_items
FOR EACH ROW EXECUTE FUNCTION capture_work_item_lifecycle();

GRANT SELECT, INSERT ON work_item_lifecycle TO botsales_runtime;
GRANT USAGE ON SEQUENCE work_item_lifecycle_event_id_seq TO botsales_runtime;

COMMIT;
